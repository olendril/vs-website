const linkedRecords: ModMetadata[] = records.map((mod) => {
  const assetId = modDbAssetIds[mod.modId];

  if (assetId === undefined) {
    throw new Error(`Missing Vintage Story ModDB asset ID for ${mod.displayName}`);
  }

  return {
    ...mod,
    externalUrl: `https://mods.vintagestory.at/show/mod/${assetId}`,
  };
});

/** Lookup records by stable slug. */
export const mods = Object.fromEntries(linkedRecords.map((mod) => [mod.slug, mod])) as Record<
  ModSlug,
  ModMetadata
>;

export const primaryMods = linkedRecords
  .filter((mod) => mod.role === 'primary')
  .sort((a, b) => a.displayName.localeCompare(b.displayName));

export const supportMods = linkedRecords
  .filter((mod) => mod.role !== 'primary')
  .sort((a, b) => a.displayName.localeCompare(b.displayName));

export const supportGroups = supportMods.reduce<Record<string, ModMetadata[]>>((groups, mod) => {
  const group = mod.parent ? mods[mod.parent].displayName : 'Shared technical packages';
  (groups[group] ??= []).push(mod);
  return groups;
}, {});

export const allMods = [...linkedRecords].sort((a, b) =>
  a.displayName.localeCompare(b.displayName),
);
