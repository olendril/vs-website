export type ModSlug = (typeof MOD_SLUGS)[keyof typeof MOD_SLUGS];
export type ModPackageRole = 'primary' | 'addon' | 'library' | 'config' | 'compatibility';

export interface ModMetadata {
  /** Stable lowercase kebab-case slug for the mod. */
  slug: ModSlug;
  /** Immediate directory name under references/, retained for inventory validation. */
  sourceDirectory: string;
  modId: string;
  displayName: string;
  description: string;
  authors: string[];
  /** Version of the mod installed on the server. */
  version: string;
  role: ModPackageRole;
  /** Related primary package for add-ons, libraries, configs, and patches. */
  parent?: ModSlug;
  relationship?: string;
  /** Public path to the bundled icon or the shared local fallback. */
  icon: `/${string}`;
  /** Vintage Story ModDB page for this installed package. */
  externalUrl: `https://mods.vintagestory.at/show/mod/${number}`;
}

